// Interne Aufgaben (core/aufgaben.js, views/aufgaben.js).
//  1. Browser-Modus (Beispieldaten): Menüpunkt „Aufgaben“ oben, Reiter mit Zahlen, Reihenfolge (Überfälliges oben),
//     neue Aufgabe anlegen (Titel, zuständig, fällig, dringend), „Erledigt“ mit einem Klick, wieder öffnen, Suche,
//     Dialog mit Kommentar und Verlauf, Löschen mit Rückfrage; Handy ohne Querscrollen.
//  2. SharePoint-Betrieb (Attrappe): Buchhaltung legt eine Aufgabe für das Büro an (Datei aufgaben/aufgaben.json), das
//     Büro sieht sie unter „Meine“ und in „Zu erledigen“, erledigt sie; ein Fahrer hat den Bereich nicht.
// Ports 19807 (Browser-Modus) und 19808 (SharePoint-Attrappe).
import { chromium, check, finish, openApp, sharepoint, startServer, wait, mondayOf, todayVienna, addDays, P } from './ablauf-lib.mjs'

const server = startServer(19807)
const server2 = startServer(19808)
await wait(800)
const browser = await chromium.launch()
const errors = []
try {
  const today = todayVienna()
  // ------------------------------------------------ 1. Browser-Modus
  const A = await openApp(browser, 19807, { errors })
  const nav = await A.state(() => [...new Set([...document.querySelectorAll('nav [data-view], .sidebar [data-view]')].map((e) => e.dataset.view))])
  check('Menü: „Aufgaben“ gleich nach der Übersicht', nav.indexOf('aufgaben') === nav.indexOf('home') + 1, nav.slice(0, 6).join(', '))
  await A.view('aufgaben')
  await A.waitFor(async () => /Angebot Autohaus Maxglan nachfassen/.test(await A.text('main')), 15000)
  let t = await A.text('main')
  const tabs = () => A.state(() => [...document.querySelectorAll('main .aufg-bar [data-action="aufg-filter"]')].map((b) => b.innerText.replace(/\s+/g, ' ').trim()))
  check('Reiter mit Zahlen: Meine 2, Alle offenen 4, Überfällig 1', JSON.stringify(await tabs()) === JSON.stringify(['Meine 2', 'Alle offenen 4', 'Überfällig 1', 'Erledigt', 'Alle']), JSON.stringify(await tabs()))
  const titles = () => A.state(() => [...document.querySelectorAll('main .aufg-row .aufg-title')].map((e) => e.textContent))
  check('„Meine“: Überfälliges oben, dann die dringende von morgen', JSON.stringify(await titles()) === JSON.stringify(['Angebot Autohaus Maxglan nachfassen', 'Schlüssel für Wohnanlage Lehen nachmachen lassen']) && /überfällig seit 2 Tagen/.test(t) && /morgen fällig/.test(t) && /dringend/.test(t) && /Autohaus Maxglan/.test(t), t.slice(0, 500))
  await A.page.click('main [data-action="aufg-filter"][data-v="offen"]')
  await wait(200)
  t = await A.text('main')
  check('„Alle offenen“: vier Aufgaben, Hinweis auf die eine ohne Zuständige', (await titles()).length === 4 && /Eine offene Aufgabe hat noch niemanden/.test(t) && /niemand/.test(t), JSON.stringify(await titles()))
  // neue Aufgabe für jemand anderen
  await A.page.click('main [data-action="aufg-new"]')
  await A.page.waitForSelector('#aufg-title')
  check('Dialog: Zuständig mit der eigenen Person vorbelegt, Vorschläge aus den Mitarbeitenden', (await A.page.inputValue('#aufg-who')) === 'Browser' && (await A.page.locator('#aufg-people option').count()) > 5)
  await A.page.click('.modal [data-action="aufg-save"]')
  await A.toastWait(/beschreiben, was zu tun ist/, 5000)
  check('Ohne Titel wird nicht gespeichert', (await A.page.locator('#aufg-title').count()) === 1)
  await A.page.fill('#aufg-title', 'Staubsauger zur Reparatur bringen')
  await A.page.fill('#aufg-who', 'Ana Popescu')
  await A.page.fill('#aufg-due', addDays(today, 3))
  await A.page.check('#aufg-prio')
  await A.page.fill('#aufg-note', 'Kabelbruch am Griff')
  await A.page.click('.modal [data-action="aufg-save"]')
  await A.toastWait(/Aufgabe angelegt/, 5000)
  const saved = await A.state(async () => (await import('/src/ui/context.js')).app.data.aufgaben.items.find((x) => x.title === 'Staubsauger zur Reparatur bringen'))
  check('Gespeichert: zuständig, fällig, dringend, Verlauf mit „angelegt“', saved?.assignee?.name === 'Ana Popescu' && saved.due === addDays(today, 3) && saved.priority === 'hoch' && saved.status === 'offen' && saved.note === 'Kabelbruch am Griff' && /^angelegt, zuständig: Ana Popescu, fällig am /.test(saved.log[0].text) && saved.createdBy === 'Browser', JSON.stringify(saved))
  check('Liste: fünf offene, die neue steht drin', (await titles()).length === 5 && (await titles()).includes('Staubsauger zur Reparatur bringen'), JSON.stringify(await titles()))
  // Suche
  await A.page.fill('#aufg-q', 'ana')
  await A.waitFor(async () => (await titles()).length === 1, 5000)
  check('Suche nach der zuständigen Person', JSON.stringify(await titles()) === JSON.stringify(['Staubsauger zur Reparatur bringen']), JSON.stringify(await titles()))
  await A.page.fill('#aufg-q', '')
  await A.waitFor(async () => (await titles()).length === 5, 5000)
  // erledigen mit einem Klick, wieder öffnen
  await A.page.click(`main .aufg-row[data-id="${saved.id}"] [data-action="aufg-status"][data-v="erledigt"]`)
  await A.toastWait(/Erledigt/, 5000)
  check('„Erledigt“: verschwindet aus den offenen, Reiter zählt neu', (await titles()).length === 4 && /Alle offenen 4/.test((await tabs()).join('|')))
  await A.page.click('main [data-action="aufg-filter"][data-v="erledigt"]')
  await wait(200)
  t = await A.text('main')
  check('„Erledigt“: neueste zuerst, mit Datum und Person', (await titles())[0] === 'Staubsauger zur Reparatur bringen' && /erledigt am .* von Browser/.test(t), t.slice(0, 400))
  await A.page.click(`main .aufg-row[data-id="${saved.id}"] [data-action="aufg-status"][data-v="offen"]`)
  await A.toastWait(/Wieder offen/, 5000)
  // Dialog: Kommentar, umhängen, Verlauf
  await A.page.click('main [data-action="aufg-filter"][data-v="offen"]')
  await wait(200)
  await A.page.click(`main .aufg-row[data-id="${saved.id}"] [data-action="aufg-open"]`)
  await A.page.waitForSelector('#aufg-comment')
  await A.page.fill('#aufg-who', 'Browser')
  await A.page.fill('#aufg-comment', 'Werkstatt hat bis Freitag Zeit')
  await A.page.click('.modal [data-action="aufg-save"]')
  await A.toastWait(/Aufgabe gespeichert/, 5000)
  await A.page.click(`main .aufg-row[data-id="${saved.id}"] [data-action="aufg-open"]`)
  await A.page.waitForSelector('.modal .aufg-log')
  t = await A.text('.modal .aufg-log')
  check('Verlauf: Kommentar, Zuständigkeit, Status in zeitlicher Folge (neueste oben)', /Werkstatt hat bis Freitag Zeit/.test(t) && /zuständig: Browser/.test(t) && /Status: erledigt/.test(t) && /Status: offen/.test(t) && /angelegt/.test(t) && t.indexOf('Werkstatt') < t.indexOf('angelegt'), t)
  await A.page.screenshot({ path: `${P}/aufgaben-dialog.png` })
  // Löschen mit Rückfrage
  await A.page.click('.modal [data-action="aufg-delete"]')
  await A.waitFor(async () => /Wirklich löschen\?/.test(await A.text('.modal [data-action="aufg-delete"]')), 5000)
  check('Löschen fragt nach', /Wirklich löschen\?/.test(await A.text('.modal [data-action="aufg-delete"]')))
  await A.page.click('.modal [data-action="aufg-delete"]')
  await A.toastWait(/Aufgabe gelöscht/, 5000)
  check('Gelöscht', !(await titles()).includes('Staubsauger zur Reparatur bringen'))
  await A.page.click('main [data-action="aufg-filter"][data-v="meine"]')
  await wait(200)
  await A.page.screenshot({ path: `${P}/aufgaben.png`, fullPage: true })
  await A.ctx.close()

  const M = await openApp(browser, 19807, { errors, mobile: true })
  await M.view('aufgaben')
  await M.waitFor(async () => /Angebot Autohaus/.test(await M.text('main')), 15000)
  const over = await M.state(() => document.documentElement.scrollWidth - window.innerWidth)
  check('Handy (390 px): ohne Querscrollen', over <= 1, String(over))
  await M.page.screenshot({ path: `${P}/aufgaben-handy.png`, fullPage: true })
  await M.ctx.close()

  // ------------------------------------------------ 2. SharePoint-Betrieb: zwei Rollen, eine Datei
  const { createDemoData } = await import('../src/data/demo.js')
  const { splitData } = await import('../src/storage/data-service.js')
  const SP = sharepoint({ access: { planners: ['office@cleanos.at'], members: { buchhaltung: ['buch@cleanos.at'], mattenfahrer: ['fahrer@cleanos.at'] } } })
  const docs = splitData(createDemoData(mondayOf(today)), [])
  delete docs['aufgaben/aufgaben.json']
  SP.seed(docs)
  const B = await SP.open(browser, 19808, { email: 'buch@cleanos.at', name: 'Berta Buch', errors, hash: '#aufgaben' })
  await B.waitFor(async () => /Noch keine Aufgaben/.test(await B.text('main')), 20000)
  check('Buchhaltung: Bereich „Aufgaben“ sichtbar, leer mit Erklärung', /Noch keine Aufgaben/.test(await B.text('main')) && (await B.page.locator('main [data-action="aufg-new"]').count()) >= 1)
  await B.page.locator('main [data-action="aufg-new"]').first().click()
  await B.page.waitForSelector('#aufg-title')
  await B.page.fill('#aufg-title', 'Zahlung Autohaus Maxglan klären')
  await B.page.fill('#aufg-who', 'Petra Leitner')
  await B.page.fill('#aufg-due', today)
  await B.page.click('.modal [data-action="aufg-save"]')
  const file = () => SP.json('aufgaben/aufgaben.json')
  check('Datei aufgaben/aufgaben.json in SharePoint mit der Aufgabe', !!(await B.waitFor(async () => file()?.items?.length === 1 && file().items[0].createdBy === 'Berta Buch' && file().items[0].assignee.name === 'Petra Leitner', 20000)), JSON.stringify(file()?.items?.[0] || null).slice(0, 300))
  t = await B.text('main')
  check('Für jemand anderen angelegt: Ansicht wechselt auf „Alle offenen“ und zeigt sie', /Zahlung Autohaus Maxglan klären/.test(t) && /heute fällig/.test(t), t.slice(0, 300))
  await B.ctx.close()

  const O = await SP.open(browser, 19808, { email: 'office@cleanos.at', name: 'Petra Leitner', errors, hash: '#aufgaben', todo: true })
  await O.waitFor(async () => /Zahlung Autohaus Maxglan klären/.test(await O.text('main')), 20000)
  const todo = await O.waitFor(async () => /Zahlung Autohaus Maxglan klären/.test(await O.text('#modal-root')) && (await O.text('#modal-root')), 20000)
  check('Büro: „Zu erledigen“ öffnet sich mit der eigenen heute fälligen Aufgabe', !!todo && /heute fällig/.test(todo), String(todo).slice(0, 300))
  await O.closeModals()
  check('Büro: steht unter „Meine“ (über den Namen der Anmeldung)', /Meine 1/.test(await O.text('main .aufg-bar')) && /Zahlung Autohaus Maxglan klären/.test(await O.text('main .aufg-list')))
  await O.page.click('main .aufg-row [data-action="aufg-status"][data-v="erledigt"]')
  check('Büro erledigt sie: in SharePoint „erledigt“ mit Person und Zeit', !!(await O.waitFor(async () => file().items[0].status === 'erledigt' && file().items[0].doneBy === 'Petra Leitner' && /T/.test(file().items[0].doneAt), 20000)), JSON.stringify(file().items[0]).slice(0, 300))
  await O.ctx.close()

  const before = SP.drive.log.length
  const F = await SP.open(browser, 19808, { email: 'fahrer@cleanos.at', name: 'Markus Huber', errors, mobile: true })
  const fs = await F.state(async () => { const c = await import('/src/ui/context.js'); return { sees: c.app.access.sees('aufgaben'), views: c.visibleViews().map((v) => v.id), denied: [...c.app.service.denied] } })
  check('Fahrer: kein Bereich „Aufgaben“, die Datei wird nicht gelesen', !fs.sees && !fs.views.includes('aufgaben') && fs.denied.includes('aufgaben/aufgaben.json') && !SP.drive.log.slice(before).some((x) => /aufgaben\/aufgaben\.json/.test(x.p)), JSON.stringify(fs.views))
  check('keine Fehler im Browser', !errors.length, errors.slice(0, 5).join(' | '))
} catch (err) {
  check('Ablauf ohne Ausnahme', false, String(err?.stack || err).slice(0, 900))
}
await finish(browser, [server, server2], errors)
