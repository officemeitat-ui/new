const WEEKDAYS = { de: ['Mo', 'Di', 'Mi', 'Do', 'Fr', 'Sa', 'So'], en: ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'], ro: ['Lu', 'Ma', 'Mi', 'Jo', 'Vi', 'Sâ', 'Du'] }

/** Übersetzer für eine Sprache: t('sec.objekt'), t('page', { p: 1, n: 2 }), t.interval('w1', 'wöchentlich'), t.weekday(1). */
export function sheetText(lang = 'de') {
  const dict = T[lang] || T.de
  const t = (key, vars = {}) => String(dict[key] ?? T.de[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '')
  t.lang = T[lang] ? lang : 'de'
  t.interval = (code, fallback) => INTERVALS[t.lang]?.[code] || fallback || code
  t.weekday = (d) => (WEEKDAYS[t.lang] || WEEKDAYS.de)[d - 1] || ''
  // Wochentage aus der Mappe („Mo“, „Di“ …) in die Sprache des Blatts
  t.dayName = (de) => {
    const i = WEEKDAYS.de.indexOf(String(de).slice(0, 2))
    return i >= 0 ? t.weekday(i + 1) : String(de)
  }
  t.locale = { de: 'de-AT', en: 'en-GB', ro: 'ro-RO' }[t.lang]
  return t
}
