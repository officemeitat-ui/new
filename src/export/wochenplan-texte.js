const fill = (text, values = {}) => String(text).replace(/\{(\w+)\}/g, (m, k) => (k in values ? String(values[k]) : m))

/**
 * Texte einer Sprache (unbekannt: Deutsch): t(Schlüssel, Werte), list(Schlüssel), hours(Minuten), date(ISO, { weekday,
 * year }), note(Hinweis der App), absence(Art), employment(Beschäftigung), objectInfo(Objekt).
 */
export function planTexts(lang) {
  const id = isLang(lang) && PLAN_TEXTS[lang] ? lang : 'de'
  const T = PLAN_TEXTS[id]
  const de = id === 'de'
  const t = (key, values) => fill(T[key] ?? PLAN_TEXTS.de[key] ?? key, values)
  const list = (key) => T[key] || PLAN_TEXTS.de[key]
  const parts = (iso) => ({ d: iso.slice(8, 10), m: iso.slice(5, 7), j: iso.slice(0, 4), wd: (new Date(`${iso}T12:00:00Z`).getUTCDay() + 6) % 7 })
  /** „Montag 26.10.“ (weekday 'lang'), „26.10.“, „26.10.2026“ (year) – je Sprache. */
  const date = (iso, { weekday = false, year = false } = {}) => {
    if (!iso) return ''
    const p = parts(iso)
    if (de) return weekday ? `${T.wochentage[p.wd]} ${formatDate(iso, { weekday: false, year })}` : formatDate(iso, { weekday: false, year })
    if (weekday) return fill(T.datum, { tag: T.wochentage[p.wd], d: p.d, m: p.m })
    return fill(year ? T.datum_jahr : T.datum_kurz, p)
  }
  /** Deutsche Datumsangaben der App („Mo 02.11.“) in der Sprache. */
  const rewriteDates = (text) => (de ? text : String(text).replace(/\b(Mo|Di|Mi|Do|Fr|Sa|So) (\d\d)\.(\d\d)\./gu, (m, wd, d, mo) => fill(T.datum, { tag: T.tage[PLAN_TEXTS.de.tage.indexOf(wd)], d, m: mo })))
  const absence = (type) => (ABSENCES[type] ? t(ABSENCES[type]) : String(type || ''))
  const note = (text) => {
    const n = String(text || '')
    if (de) return n
    for (const [re, key] of NOTE_PATTERNS) {
      const hit = re.exec(n)
      if (!hit) continue
      const v = { ...hit.groups }
      if (v.datum) v.datum = rewriteDates(v.datum)
      if (v.art) v.art = absence(v.art)
      if (v.ziel === 'nächstem Einsatz') v.ziel = t('naechster_einsatz')
      return t(key, v)
    }
    if (ABSENCES[n]) return absence(n)
    return rewriteDates(n)
  }
  return {
    lang: id,
    t,
    list,
    date,
    note,
    absence,
    /** Stunden mit dem Dezimalzeichen der Sprache: „7,5“ bzw. „7.5“. */
    hours: (min) => formatHours(min).replace(',', T.dezimal),
    employment: (type) => (TYPES[type] ? t(TYPES[type]) : String(type || '')),
    /** Objektanweisung: Übersetzung, solange sie zum deutschen Text passt; sonst der deutsche Text. */
    objectInfo: (obj) => {
      const german = String(obj?.instructions || '').trim()
      const tr = de ? null : obj?.instructionsI18n?.[id]
      return tr?.text?.trim() && tr.source === sourceKey(german) ? tr.text.trim() : german
    },
  }
}
